async function changeLanguage(lang) {
    const elements = document.querySelectorAll("[data-translate]");
    elements.forEach((el) => {
      const key = el.getAttribute("data-translate");
      const translation = translations[lang][key];
  
      // Verifica se é um campo de formulário com placeholder
      if ((el.tagName === "INPUT" || el.tagName === "TEXTAREA") && el.hasAttribute("placeholder")) {
        el.placeholder = translation || key;
      } 
      // Verifica se é um botão de envio (submit)
      else if (el.tagName === "INPUT" && el.type === "submit") {
        el.value = translation || key;
      } 
      // Verifica se o conteúdo tem HTML
      else if (translation && translation.includes("<")) {
        el.innerHTML = translation;
      } 
      // Caso geral, atualiza o texto
      else {
        el.textContent = translation || key;
      }
    });
  
    localStorage.setItem("language", lang);
  }
  

document.addEventListener("DOMContentLoaded", () => {
  const savedLanguage = localStorage.getItem("language") || "pt";
  changeLanguage(savedLanguage);
});
